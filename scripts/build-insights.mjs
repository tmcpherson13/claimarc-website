#!/usr/bin/env node
/**
 * build-insights — scans public/insights/ and produces:
 *   - src/content/insights.generated.ts  (the runtime manifest)
 *   - public/sitemap.xml                 (regenerated with insight URLs)
 *
 * Publishing workflow for non-developers:
 *   1. Drop the PDF into  public/insights/  named like
 *        2026-04-15_payer-denial-trends.pdf
 *      (pattern: YYYY-MM-DD_slug.pdf)
 *   2. Optionally drop a matching JSON sidecar with richer metadata:
 *        public/insights/2026-04-15_payer-denial-trends.json
 *        {
 *          "title": "Payer Denial Trends — Q1 2026",
 *          "summary": "A 12-page review of...",
 *          "tags": ["denials", "research"],
 *          "author": "ClaimARC Research"
 *        }
 *   3. Commit / push — the next build regenerates the manifest and
 *      sitemap automatically.
 *
 * No JSON sidecar? The script falls back to a title derived from the
 * filename and a generic placeholder summary.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const INSIGHTS_DIR = path.join(ROOT, "public", "insights");
const OUT_TS = path.join(ROOT, "src", "content", "insights.generated.ts");
const OUT_SITEMAP = path.join(ROOT, "public", "sitemap.xml");

const SITE_URL = "https://www.claimarc.com";

/** Static routes that must always be in the sitemap. */
const STATIC_ROUTES = [
  { loc: "/",               freq: "weekly",  priority: "1.0" },
  { loc: "/accelerator",    freq: "monthly", priority: "0.9" },
  { loc: "/eob-conversion", freq: "monthly", priority: "0.9" },
  { loc: "/era-processing", freq: "monthly", priority: "0.9" },
  { loc: "/why-claimarc",   freq: "monthly", priority: "0.8" },
  { loc: "/leadership",     freq: "monthly", priority: "0.7" },
  { loc: "/contact",        freq: "monthly", priority: "0.7" },
  { loc: "/insights",       freq: "weekly",  priority: "0.8" },
];

/** Filename pattern: YYYY-MM-DD_slug.pdf (date optional). */
const FILENAME = /^(?:(\d{4}-\d{2}-\d{2})_)?([a-z0-9][a-z0-9-]+)\.pdf$/i;

function titleCaseFromSlug(slug) {
  return slug
    .replace(/-/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

function scan() {
  if (!fs.existsSync(INSIGHTS_DIR)) {
    fs.mkdirSync(INSIGHTS_DIR, { recursive: true });
  }

  const entries = [];
  for (const name of fs.readdirSync(INSIGHTS_DIR)) {
    const m = FILENAME.exec(name);
    if (!m) continue; // ignores README, sidecar .json files, etc.
    const [, date, slug] = m;
    const pdfRel = `/insights/${name}`;
    const sidecarPath = path.join(INSIGHTS_DIR, name.replace(/\.pdf$/i, ".json"));

    let meta = {};
    if (fs.existsSync(sidecarPath)) {
      try {
        meta = JSON.parse(fs.readFileSync(sidecarPath, "utf8"));
      } catch (err) {
        console.warn(`[build-insights] could not parse ${sidecarPath}: ${err.message}`);
      }
    }

    const stat = fs.statSync(path.join(INSIGHTS_DIR, name));

    entries.push({
      slug,
      date: meta.date || date || stat.mtime.toISOString().slice(0, 10),
      title: meta.title || titleCaseFromSlug(slug),
      summary:
        meta.summary ||
        "A ClaimARC research paper. Open the PDF for the full analysis.",
      tags: Array.isArray(meta.tags) ? meta.tags : [],
      author: meta.author || "ClaimARC Research",
      pdf: pdfRel,
      ogImage: meta.ogImage || "/brand/claimarc-stacked-color.png",
      sizeBytes: stat.size,
    });
  }

  // Newest first.
  entries.sort((a, b) => (a.date < b.date ? 1 : -1));
  return entries;
}

function writeManifest(entries) {
  fs.mkdirSync(path.dirname(OUT_TS), { recursive: true });
  const body =
    "// Auto-generated by scripts/build-insights.mjs — do not edit by hand.\n" +
    "// Regenerated on every build from PDFs in /public/insights/.\n\n" +
    "export interface Insight {\n" +
    "  slug: string;\n" +
    "  date: string;\n" +
    "  title: string;\n" +
    "  summary: string;\n" +
    "  tags: string[];\n" +
    "  author: string;\n" +
    "  pdf: string;\n" +
    "  ogImage: string;\n" +
    "  sizeBytes: number;\n" +
    "}\n\n" +
    "export const insights: Insight[] = " +
    JSON.stringify(entries, null, 2) +
    ";\n";
  fs.writeFileSync(OUT_TS, body);
}

function writeSitemap(entries) {
  const lines = ['<?xml version="1.0" encoding="UTF-8"?>'];
  lines.push('<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">');
  for (const r of STATIC_ROUTES) {
    lines.push("  <url>");
    lines.push(`    <loc>${SITE_URL}${r.loc}</loc>`);
    lines.push(`    <changefreq>${r.freq}</changefreq>`);
    lines.push(`    <priority>${r.priority}</priority>`);
    lines.push("  </url>");
  }
  for (const e of entries) {
    lines.push("  <url>");
    lines.push(`    <loc>${SITE_URL}/insights/${e.slug}</loc>`);
    lines.push(`    <lastmod>${e.date}</lastmod>`);
    lines.push("    <changefreq>yearly</changefreq>");
    lines.push("    <priority>0.6</priority>");
    lines.push("  </url>");
  }
  lines.push("</urlset>");
  lines.push("");
  fs.writeFileSync(OUT_SITEMAP, lines.join("\n"));
}

const entries = scan();
writeManifest(entries);
writeSitemap(entries);
console.log(
  `[build-insights] manifest: ${entries.length} entr${entries.length === 1 ? "y" : "ies"} written to src/content/insights.generated.ts`,
);
console.log(`[build-insights] sitemap: ${STATIC_ROUTES.length + entries.length} URLs written to public/sitemap.xml`);
